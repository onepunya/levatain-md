export const ITEM_LIST = Object.keys(ITEMS);
export const MAX_INVENTORY = 24;

export function getItem(id) {
    return ITEMS[id] || null;
}

export function rollDrops(monsterId) {
    const drops = [];
    for (const id of ITEM_LIST) {
        const item = ITEMS[id];
        if (!item.dropFrom?.includes(monsterId)) continue;
        if (Math.random() < (item.dropChance || 0)) {
            drops.push(id);
        }
    }
    return drops;
}
